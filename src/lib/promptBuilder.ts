import type { MediaType } from '../types'
import type { Settings } from './settings'

export function systemPrompt(s: Settings): string {
  const youtube = s.youtubeChannel.trim()
    ? `\n- Последнее предложение описания — короткий призыв перейти на YouTube: для видео — посмотреть полную версию, для фото — найти больше идей на канале.`
    : ''
  return `Ты — эксперт по поисковой оптимизации пинов в Pinterest, ниша аккаунта: «${s.niche}».
По приложенным кадрам напиши пин на языке: ${s.language}.

Pinterest работает как поисковик: пин находят по запросам, поэтому важны ключевые фразы, которые люди действительно ищут.

Требования:
- title: до 100 символов. Начинается с главной ключевой фразы, дальше — конкретная польза или деталь. Без кликбейта, эмодзи и кавычек.
- description: 2–4 естественных предложения, до 450 символов. 2–3 ключевые фразы, главная — в первом предложении. Описывай только то, что действительно видно на кадрах.${youtube}
- topics: от 5 до 10 тем для поля «темы» в Pinterest — короткие поисковые фразы из 1–3 слов, без символа #.
- Не используй хэштеги ни в title, ни в description.
- Пиши грамотно: проверь орфографию и пунктуацию.
- Соблюдай правила Pinterest: без спама, обещаний, которые вводят в заблуждение, и чувствительных тем.

Ответь строго валидным JSON без markdown и пояснений:
{"title": "...", "description": "...", "topics": ["...", "..."]}`
}

export function userPrompt(type: MediaType): string {
  return type === 'video'
    ? 'Это три кадра из одного видео: начало, середина и конец. Верни JSON для пина.'
    : 'Это фото для пина. Верни JSON для пина.'
}
